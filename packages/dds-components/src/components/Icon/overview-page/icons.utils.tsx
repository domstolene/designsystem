export function filterIcons(
  query: string,
  allIcons: typeof icons,
  activeCategories: Set<IconCategory>,
): Array<[IconName, SvgIcon]> {
  const q = query.toLowerCase().trim();

  return Object.entries(allIcons).filter(([name]) => {
    const meta = iconMeta[trimIconName(name as IconName)];
    const matchesName = !q || name.toLowerCase().includes(q);
    const matchesTags =
      !q || (meta?.tags ?? []).some(tag => tag.toLowerCase().includes(q));
    const matchesCategory =
      activeCategories.size === 0 ||
      (meta?.category !== undefined && activeCategories.has(meta.category));

    return (matchesName || matchesTags) && matchesCategory;
  }) as Array<[IconName, SvgIcon]>;
}
